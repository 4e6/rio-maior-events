#!/usr/bin/env python3
"""Generate src/py/unicode.generated.ts: Python str tables the JS runtime lacks.

Run with the reference Python (3.14): python3.14 tools/gen_unicode.py
"""
import json
import os
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = not (0xD800 <= cp <= 0xDFFF) and pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out += [start, cp - 1]
            start = None
    if start is not None:
        out += [start, 0x10FFFF]
    return out


fold = {}
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp)
    if c.casefold() != c:
        fold[cp] = c.casefold()

lines = [
    "// Generated by tools/gen_unicode.py from Python %s (Unicode %s). Do not edit." % (sys.version.split()[0], unicodedata.unidata_version),
    "// Ranges are flat [start, end, start, end, ...] inclusive, sorted.",
    "export const ISALNUM_RANGES: number[] = %s;" % json.dumps(ranges(str.isalnum)),
    "export const ISDIGIT_RANGES: number[] = %s;" % json.dumps(ranges(str.isdigit)),
    "export const COMBINING_RANGES: number[] = %s;" % json.dumps(ranges(lambda c: unicodedata.combining(c) != 0)),
    "// code point -> str.casefold() of it, for every code point whose casefold differs from itself.",
    "export const CASEFOLD: Record<number, string> = %s;" % json.dumps({str(k): v for k, v in fold.items()}, ensure_ascii=True),
]
dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "py", "unicode.generated.ts")
with open(dest, "w") as f:
    f.write("\n".join(lines) + "\n")
print(len(fold), "casefold entries")
